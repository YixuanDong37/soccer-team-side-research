import pandas as pd, numpy as np
pd.set_option("display.width", 280); pd.set_option("display.max_columns", 80); pd.set_option("display.max_rows", 300)
df = pd.read_csv("out/returns.csv")
sc = df[df.status == "scored"].copy()
for k in ("is_candidate", "same_plugin"): sc[k] = sc[k].astype(bool)
print("kinds A x B (scored)"); print(pd.crosstab(sc.a_kind, sc.b_kind, margins=True))
print(pd.crosstab([sc.a_kind, sc.b_kind], sc.ceiling_class))
print("anchors exist (all 167):"); print(pd.crosstab(df.status, [df.anchor_a.notna(), df.anchor_b.notna()]))
both = df[df.anchor_a.notna() & df.anchor_b.notna()].copy()
print("anchors same piece:", both.anchors_same_piece.value_counts().to_dict(), "same plugin:", both.anchors_same_plugin.value_counts().to_dict())
print(pd.crosstab(both.status, both.anchors_same_piece))
d = both[both.anchors_same_piece == False].copy()
print("anchor pairs (different pieces):", len(d))
print("candidate:", d.anchors_candidate.value_counts().to_dict())
print(d.anchors_not_candidate_why.fillna("").value_counts())
print("mutual status:"); print(d.anchors_mutual_status.value_counts())
print("pathG:"); print(d.anchors_pathG.value_counts())
print("desc kinds:"); print(d.anchors_desc_kinds.value_counts())
print("lead/delay:"); print(d.anchor_a_lead_frames.describe()); print(d.anchor_b_delay_frames.describe())
print((d.anchor_a_lead_frames > 12).sum(), (d.anchor_b_delay_frames > 12).sum())
print("cos any:"); print(d.anchors_cos_any.describe())
print("true minus best impostor:"); print(d.true_minus_best_impostor.describe()); 
for th in (0, 0.02, 0.05, 0.1): print(th, (d.true_minus_best_impostor >= th).sum(), "of", d.true_minus_best_impostor.notna().sum())
print("sides:"); print(pd.crosstab(d.anchor_a_end_side, d.anchor_b_start_side))
print("exit/reentry side ann:"); print(pd.crosstab(df.exit_side, df.reentry_side))
print("speed:"); print(d.anchors_sys_speed_mps.describe()); print(df.ann_speed_mps.describe()); print("reach ok", d.anchors_reach_ok.value_counts(dropna=False).to_dict())
print("gap_s (anchor piece gap):"); print(d.anchors_piece_gap_s.describe()); print((d.anchors_piece_gap_s > 10).sum())
